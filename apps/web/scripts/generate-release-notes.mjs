import { execFileSync } from 'child_process';
import { existsSync, readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, '../../..');
const outputPath = join(__dirname, '../src/generated/releaseNotes.ts');

/** How many releases back the What's New drafting can reach */
const RELEASES_KEPT = 200;

/** Changelog sections members might care about, and the update type each becomes */
const SECTIONS = {
  Features: 'feature',
  Improvements: 'improvement',
  'Performance Improvements': 'improvement',
  'Bug Fixes': 'fix',
};

/**
 * The "Staff notes:" bullets in a commit's message, as the Slack post reads them
 *
 * Vercel clones shallowly, so an older commit may be missing: that just means
 * no notes, and the draft is written from the subject alone.
 *
 * @param hash - The commit, as linked in CHANGELOG.md
 * @returns The bullet texts, without their dashes
 */
const staffNotes = (hash) => {
  let message;
  try {
    message = execFileSync('git', ['show', '-s', '--format=%B', hash], {
      encoding: 'utf8',
      cwd: repoRoot,
      stdio: ['ignore', 'pipe', 'ignore'],
    });
  } catch {
    return [];
  }

  const notes = [];
  let inNotes = false;
  for (const raw of message.split('\n')) {
    const line = raw.trim();
    if (/^staff notes:?$/i.test(line)) {
      inNotes = true;
      continue;
    }
    if (!inNotes) continue;
    if (/^[-*•]\s+/.test(line)) notes.push(line.replace(/^[-*•]\s+/, ''));
    else if (!line || /^[A-Za-z-]+:\s/.test(line)) inNotes = false;
    else if (notes.length) notes[notes.length - 1] += ` ${line}`;
  }
  return notes;
};

/**
 * Bundle the recent releases into the app at build time
 *
 * What's New drafts member updates from these. They are bundled rather than
 * read from disk at run time because the deployed functions do not carry
 * CHANGELOG.md or the git history.
 */
const generateReleaseNotes = () => {
  const changelogPath = join(repoRoot, 'CHANGELOG.md');
  const items = [];

  if (existsSync(changelogPath)) {
    const releases = readFileSync(changelogPath, 'utf8')
      .split(/^#{1,2} \[/m)
      .slice(1, RELEASES_KEPT + 1);

    for (const release of releases) {
      const version = release.slice(0, release.indexOf(']'));
      const date = /\((\d{4}-\d{2}-\d{2})\)/.exec(release.split('\n')[0])?.[1] ?? '';

      for (const block of release.split(/^### /m).slice(1)) {
        const [heading, ...body] = block.split('\n');
        const type = SECTIONS[heading.trim()];
        if (!type) continue;

        for (const line of body.filter((l) => l.startsWith('* '))) {
          const hash = /\(\[([0-9a-f]{7,})\]\(/.exec(line)?.[1];
          const text = line
            .slice(2)
            .replace(/\s*\(\[[0-9a-f]{7,}\]\([^)]*\)\)/g, '')
            .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
            .replace(/^\*\*[^*]+:\*\*\s*/, '')
            .trim();
          if (!hash || !text) continue;
          items.push({ version, date, type, hash, text, notes: staffNotes(hash) });
        }
      }
    }
  } else {
    console.warn('⚠ CHANGELOG.md not found; What\'s New has no releases to draft from');
  }

  const content = `// Auto-generated by scripts/generate-release-notes.mjs at build time - do not edit manually
import type { ReleaseNote } from '@/app/_productUpdates/types';

const RELEASE_NOTES: ReleaseNote[] = ${JSON.stringify(items, null, 2)};

export default RELEASE_NOTES;
`;

  writeFileSync(outputPath, content, 'utf-8');
  console.log(`✓ Generated ${items.length} release notes for What's New`);
};

generateReleaseNotes();
